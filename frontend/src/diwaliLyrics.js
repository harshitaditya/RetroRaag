/**
 * Returns synchronized lyric lines for a given song title.
 */
export function getDiwaliLyrics(title = "") {
  const norm = String(title || "").toLowerCase();

  if (norm.includes("hum katha sunate") || norm.includes("katha sunate") || norm.includes("sakal gun")) {
    return DIWALI_LYRICS_DATA.hum_katha_sunate;
  }
  if (norm.includes("raghunath") || norm.includes("hamare sath") || norm.includes("kis baat ki chinta")) {
    return DIWALI_LYRICS_DATA.hamare_sath_raghunath;
  }
  if (norm.includes("ratte ratte") || norm.includes("shabari") || norm.includes("shabri")) {
    return DIWALI_LYRICS_DATA.rama_rama_ratte_ratte;
  }
  if (norm.includes("pragat kripala") || norm.includes("bhaye pragat")) {
    return DIWALI_LYRICS_DATA.bhaye_pragat_kripala;
  }
  if (norm.includes("thumak") || norm.includes("chalat ramchandra") || norm.includes("painjaniya")) {
    return DIWALI_LYRICS_DATA.thumak_chalat_ramchandra;
  }
  if (norm.includes("nagari ho") || norm.includes("nagri ho")) {
    return DIWALI_LYRICS_DATA.nagri_ho_ayodhya;
  }
  if (norm.includes("lakshmi mata") || norm.includes("laxmi mata") || (norm.includes("aarti") && norm.includes("lakshmi"))) {
    return DIWALI_LYRICS_DATA.lakshmi_aarti;
  }
  if (norm.includes("ganesh") || norm.includes("ganpati")) {
    if (norm.includes("sukhkarta")) return DIWALI_LYRICS_DATA.sukhkarta_dukhharta;
    return DIWALI_LYRICS_DATA.ganesh_aarti;
  }
  if (norm.includes("jagdish")) {
    return DIWALI_LYRICS_DATA.jagdish_hare;
  }
  if (norm.includes("raghuvar") || (norm.includes("ram") && norm.includes("aarti"))) {
    return DIWALI_LYRICS_DATA.ram_aarti;
  }
  if (norm.includes("mangal bhavan") || norm.includes("ram siya ram")) {
    return DIWALI_LYRICS_DATA.mangal_bhavan;
  }
  if (norm.includes("kuber")) {
    return DIWALI_LYRICS_DATA.kuber_aarti;
  }
  if (norm.includes("dhanvantari")) {
    return DIWALI_LYRICS_DATA.dhanvantari_aarti;
  }
  if (norm.includes("shriman narayan") || norm.includes("narayan")) {
    return DIWALI_LYRICS_DATA.shriman_narayan;
  }
  if (norm.includes("hanuman") || norm.includes("chalisa")) {
    if (norm.includes("laxmi") || norm.includes("lakshmi")) return DIWALI_LYRICS_DATA.laxmi_chalisa;
    return DIWALI_LYRICS_DATA.hanuman_chalisa;
  }
  if (norm.includes("ramchandra kripalu")) {
    return DIWALI_LYRICS_DATA.shri_ramchandra_kripalu;
  }
  if (norm.includes("ashtakam")) {
    return DIWALI_LYRICS_DATA.mahalakshmi_ashtakam;
  }
  if (norm.includes("chalisa")) {
    return DIWALI_LYRICS_DATA.laxmi_chalisa;
  }
  if (norm.includes("kunj bihari") || norm.includes("krishna")) {
    return DIWALI_LYRICS_DATA.kunj_bihari;
  }
  if (norm.includes("ambe gauri") || norm.includes("durga")) {
    return DIWALI_LYRICS_DATA.ambe_gauri;
  }
  if (norm.includes("mantra") && (norm.includes("lakshmi") || norm.includes("mahalakshmi"))) {
    return DIWALI_LYRICS_DATA.mahalakshmi_mantra;
  }
  if (norm.includes("ghar mein") || norm.includes("mere ghar")) {
    return DIWALI_LYRICS_DATA.mata_lakshmi_ghar;
  }
  if (norm.includes("raja ram") || norm.includes("ghar aaye")) {
    return DIWALI_LYRICS_DATA.raja_ram_ghar;
  }

  // Fallback to Mangal Bhavan for Ram Katha / spiritual
  if (norm.includes("ram") || norm.includes("katha") || norm.includes("ayodhya")) {
    return DIWALI_LYRICS_DATA.mangal_bhavan;
  }

  return DIWALI_LYRICS_DATA.lakshmi_aarti;
}

